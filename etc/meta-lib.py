#!/usr/bin/env python3
"""Generate the `PerennialMeta` library: Perennial's proof automation, compiled
to native code.

Lean runs a tactic, elaborator, macro, simproc or notation by interpreting its
compiled IR, unless the module defining it was precompiled to a shared library
that `lean` loads. Precompiling the whole package costs more C compilation
than it saves, so `lakefile.toml` declares a second library, `PerennialMeta`,
with `precompileModules = true`, holding only

* the seeds: every module outside the per-program directories (`Perennial/Code`,
  `GeneratedProof`, `Spec`, `Proof`, `ManualProof`, `TrustedCode`) that defines
  code run at elaboration time (`syntax`, `macro`, `elab`, `notation`,
  `simproc`, `initialize`, `register_*_attr`, `meta` definitions, unexpanders,
  ...), erring on the side of inclusion;
* everything they import, so the library is closed under imports: a native
  module cannot import a module that is not native.

A module listed there stays an ordinary `Perennial` module for everything else
(`lake build Perennial.X` works as before); lake uses the last declared library
that contains a module, so `PerennialMeta` comes after `Perennial`.

Lake loads a library with precompiled modules as one shared library, linked
from its root, so the library has exactly one root, `PerennialMeta.lean`, which
imports every listed module.

Usage: etc/meta-lib.py           rewrite the list in lakefile.toml and PerennialMeta.lean
       etc/meta-lib.py --check   exit 1 if either is out of date (lean-ci.sh, land.sh run it)
       etc/meta-lib.py --list    print the seeds and the closure
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAKEFILE = os.path.join(ROOT, "lakefile.toml")
AGGREGATOR = os.path.join(ROOT, "PerennialMeta.lean")
BEGIN = "# BEGIN generated by etc/meta-lib.py"
END = "# END generated by etc/meta-lib.py"

# Directories of per-program code and proofs: their local macros stay interpreted.
PROGRAM_DIRS = ("Code", "GeneratedProof", "Spec", "Proof", "ManualProof", "TrustedCode")

MODIFIERS = r"(?:(?:private|public|protected|scoped|local|noncomputable|partial|unsafe|meta)\s+)*"
SEED_RE = re.compile(
    r"^\s*(?:@\[[^\]]*\]\s*)?" + MODIFIERS +
    r"(?:syntax|macro|macro_rules|elab|elab_rules|notation|infix|infixl|infixr|prefix|postfix"
    r"|simproc|dsimproc|simproc_decl|dsimproc_decl|declare_syntax_cat|declare_simp_like_tactic"
    r"|register_\w+|initialize|builtin_initialize)\b"
    r"|^\s*(?:public\s+|private\s+)?meta\s+(?:def|import|section|instance|structure|inductive|partial|opaque)\b"
    r"|@\[(?:[^\]]*\s)?(?:app_unexpander|delab|tactic|term_elab|command_elab|simproc|macro)\b",
    re.M)
IMPORT_RE = re.compile(r"^\s*(?:public\s+)?(?:meta\s+)?import\s+(?:all\s+)?(\S+)", re.M)


def module_of(path):
    return os.path.relpath(path, ROOT)[: -len(".lean")].replace(os.sep, ".")


def file_of(mod):
    return os.path.join(ROOT, *mod.replace("«", "").replace("»", "").split(".")) + ".lean"


def strip_comments(src):
    src = re.sub(r"/-.*?-/", "", src, flags=re.S)  # block and doc comments (no nesting in practice)
    return re.sub(r"--.*", "", src)


def imports(mod):
    with open(file_of(mod), encoding="utf-8") as f:
        src = strip_comments(f.read())
    out = []
    for m in IMPORT_RE.finditer(src):
        imp = m.group(1).replace("«", "").replace("»", "")
        if (imp == "Perennial" or imp.startswith("Perennial.")) and os.path.exists(file_of(imp)):
            out.append(imp)
    return out


def seeds():
    out = []
    base = os.path.join(ROOT, "Perennial")
    for dirpath, dirnames, filenames in os.walk(base):
        if dirpath == base:
            dirnames[:] = [d for d in dirnames if d not in PROGRAM_DIRS]
        for fn in filenames:
            if fn.endswith(".lean"):
                p = os.path.join(dirpath, fn)
                with open(p, encoding="utf-8") as f:
                    if SEED_RE.search(strip_comments(f.read())):
                        out.append(module_of(p))
    return sorted(out)


def closure(roots):
    seen, stack = set(), list(roots)
    while stack:
        m = stack.pop()
        if m not in seen:
            seen.add(m)
            stack.extend(imports(m))
    return sorted(seen)


def quote(mod):
    """Quote the components lake's TOML globs and `import` need quoted («unsafe»)."""
    return ".".join(c if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*", c) else f"«{c}»"
                    for c in mod.split("."))


def render(mods):
    globs = "globs = [\n" + "".join(f'  "{quote(m)}",\n' for m in ["PerennialMeta"] + mods) + "]\n"
    agg = ("module\n\n"
           "-- Generated by etc/meta-lib.py: the root of the `PerennialMeta` library (see lakefile.toml).\n\n"
           + "".join(f"public import {quote(m)}\n" for m in mods))
    with open(LAKEFILE, encoding="utf-8") as f:
        lake = f.read()
    i, j = lake.find(BEGIN), lake.find(END)
    if i < 0 or j < i:
        sys.exit(f"meta-lib: lakefile.toml lacks the '{BEGIN}' ... '{END}' markers")
    lake = lake[: i + len(BEGIN)] + "\n" + globs + lake[j:]
    return lake, agg


def main():
    args = sys.argv[1:]
    s = seeds()
    mods = closure(s)
    if args == ["--list"]:
        print("# seeds"); print("\n".join(s))
        print("# closure"); print("\n".join(mods))
        return
    lake, agg = render(mods)
    cur_agg = open(AGGREGATOR, encoding="utf-8").read() if os.path.exists(AGGREGATOR) else ""
    cur_lake = open(LAKEFILE, encoding="utf-8").read()
    if args == ["--check"]:
        if (cur_lake, cur_agg) != (lake, agg):
            sys.exit("meta-lib: the PerennialMeta module list (lakefile.toml, PerennialMeta.lean) is out of\n"
                     "date with the sources (a tactic module or one of its imports changed).\n"
                     "Fix: python3 etc/meta-lib.py, and commit the result.")
        return
    if args:
        sys.exit(__doc__)
    if cur_lake != lake:
        open(LAKEFILE, "w", encoding="utf-8").write(lake)
    if cur_agg != agg:
        open(AGGREGATOR, "w", encoding="utf-8").write(agg)
    print(f"meta-lib: {len(s)} seed modules, {len(mods)} modules in PerennialMeta")


if __name__ == "__main__":
    main()
