"""Sweep: remaining tokens equal to a renamed multi-word old short name, when no
surviving constant has that short name, are replaced (quotations, try-simp lists,
comments, docstrings)."""
import re, subprocess, sys, collections

ren = [l.rstrip("\n").split("\t") for l in open(sys.argv[1], encoding="utf-8") if "\t" in l]
inv = [l.rstrip("\n").split("\t")[1] for l in open(sys.argv[2], encoding="utf-8")]


def split_name(n):
    return re.split(r"\.(?![^«]*»)", n)


renamed = {o for o, _ in ren}
surviving_short = collections.Counter(split_name(n)[-1] for n in inv if n not in renamed)
m = collections.defaultdict(set)
for o, n in ren:
    lo, ln = split_name(o)[-1], split_name(n)[-1]
    if lo != ln and "_" in lo.strip("_") and len(split_name(n)) == len(split_name(o)):
        m[lo].add(ln)
ext = set(open(sys.argv[3]).read().split()) if len(sys.argv) > 3 else set()
rep = {k: next(iter(v)) for k, v in m.items() if len(v) == 1 and surviving_short[k] == 0 and k not in ext}
print("sweep vocabulary:", len(rep))
pat = re.compile(r"(?<![\w'])(" + "|".join(map(re.escape, sorted(rep, key=len, reverse=True))) + r")(?![\w'])")
files = subprocess.run(["git", "ls-files", "Perennial/*.lean", "docs/*.md", "PORTING.md"], capture_output=True,
                       text=True).stdout.split()
tot = collections.Counter()
for f in files:
    if f.startswith(("Perennial/Code/", "Perennial/GeneratedProof/", "Perennial/TrustedCode/", "Perennial/ManualProof/")):
        continue
    s = open(f, encoding="utf-8").read()
    if s.startswith("-- autogenerated"):
        continue
    ns, c = pat.subn(lambda mm: rep[mm.group(1)], s)
    if c:
        tot[f] = c
        open(f, "w", encoding="utf-8").write(ns)
print("replaced", sum(tot.values()), "in", len(tot), "files")
for f, c in tot.most_common(15):
    print(" ", c, f)
