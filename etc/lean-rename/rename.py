#!/usr/bin/env python3
"""Rename hand-written Lean port declarations to Lean naming conventions.

Usage: etc/lean-rename/rename.py INVENTORY.tsv [--ilean DIR] [--apply] [--report FILE]

Pipeline used for phase 1 (from a clean, fully built tree; keep a copy of the
.ilean files first, since a failing rebuild deletes them):
  lake env lean --run etc/lean-rename/inventory.lean MODULES... > inv.tsv
  etc/lean-rename/rename.py inv.tsv --ilean ILEANS --apply   # writes renames.tsv
  etc/lean-rename/namespaces.py etc/lean-rename/renames.tsv inv.tsv   # namespace/section/open/end lines
  etc/lean-rename/qualified.py etc/lean-rename/renames.tsv            # qualified names in quotations
  etc/lean-rename/sweep.py etc/lean-rename/renames.tsv inv.tsv EXTERNAL_NAMES  # leftovers, docs
  then build, and `errfix.py renames.tsv BUILD_LOG` on the errors until clean.
EXTERNAL_NAMES lists the short names of non-Perennial constants (iris-lean,
Lean), which the sweep must not touch.

INVENTORY.tsv: one line per Perennial constant, `module<TAB>name<TAB>kind<TAB>sort`
(kind: thm/def/axiom/opaque/class/structure/inductive/ctor/proj/instance/rec;
sort: what the type ends in: Prop (a predicate), Type, proof (a theorem-like
statement) or term), as dumped by a small `lake env lean --run` script.

References come from the `.ilean` files of a full build (`.lake/build/lib/lean`),
which record the exact source range of every definition and every use of every
global constant, so only real references are rewritten (not local variables that
happen to share a name).

Rules (Lean core / Mathlib / iris-lean conventions):
* classes, structures, inductives and `Type`-valued defs: UpperCamelCase;
* `Prop`-valued defs: UpperCamelCase;
* other defs (including `IProp`-valued ones), data fields, constructors:
  lowerCamelCase;
* theorems, Prop-valued instances and other proofs: snake_case, where an embedded
  multi-word name of a renamed declaration is written in lowerCamelCase
  (`own_slice_len` -> `ownSlice_len`); `wp_T__M` (spec of method `M` of Go type
  `T`) -> `T.wp_M`, and any other `__` -> `_`.

Phase 1 only renames hand-written declarations: names defined in `Code/`,
`GeneratedProof/`, `TrustedCode/`, `ManualProof/` or any file starting with
`-- autogenerated`, names used by such files (goose/proofgen would regenerate
the old names), names with Rocq-style encodings (`«…ⁱᵐᵖˡ»`, inner primes) and the
`.t` struct-value encoding are kept.
"""
import argparse, collections, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
ILEAN = os.path.join(ROOT, ".lake/build/lib/lean")

ap = argparse.ArgumentParser()
ap.add_argument("inventory")
ap.add_argument("--apply", action="store_true")
ap.add_argument("--report", default=None)
ap.add_argument("--include-generated", action="store_true",
                help="phase B: also rename names used by generated code, rewriting the generated files "
                     "(goose/proofgen must be changed to emit the new names)")
ap.add_argument("--encodings", action="store_true",
                help="phase B2: replace the Rocq-style name encodings of generated declarations "
                     "(«Xⁱᵐᵖˡ», «T__Mⁱᵐᵖˡ», X'fds, X'init, X_Assumptions) by Lean namespaces")
ap.add_argument("--no-generated-edits", action="store_true",
                help="with --include-generated: plan renames as usual but edit only hand-written files "
                     "(the generated files come from goose)")
ap.add_argument("--ilean", default=None, help="directory holding the .ilean files (default: .lake/build/lib/lean)")
args = ap.parse_args()


def split_name(n):
    return re.split(r"\.(?![^«]*»)", n)


def mod_path(m):
    return os.path.join(ROOT, *m.replace("«", "").replace("»", "").split(".")) + ".lean"


GEN_DIRS = ("Perennial.Code.", "Perennial.GeneratedProof.", "Perennial.TrustedCode.",
            "Perennial.ManualProof.")
_gen_cache = {}


def is_generated(m):
    if m in _gen_cache:
        return _gen_cache[m]
    g = m.startswith(GEN_DIRS)
    if not g:
        p = mod_path(m)
        try:
            with open(p, encoding="utf-8") as f:
                g = f.readline().startswith("-- autogenerated")
        except FileNotFoundError:
            g = True
    _gen_cache[m] = g
    return g


# ---------------------------------------------------------------- inventory
inv = {}
for line in open(args.inventory, encoding="utf-8"):
    m, n, k, s = line.rstrip("\n").split("\t")
    inv[n] = (m, k, s)

# ---------------------------------------------------------------- ileans
if args.ilean:
    ILEAN = args.ilean
defs = {}                       # name -> (module, range)
uses = collections.defaultdict(list)   # name -> [(module, range)]
for dp, _, fs in os.walk(os.path.join(ILEAN, "Perennial")):
    for f in fs:
        if not f.endswith(".ilean"):
            continue
        d = json.load(open(os.path.join(dp, f), encoding="utf-8"))
        mod = d["module"]
        if not os.path.exists(mod_path(mod)):
            continue        # stale build output of a deleted module
        for key, v in d["references"].items():
            c = json.loads(key).get("c")
            if not c:
                continue
            n = c["n"]
            if v.get("definition") and c["m"] == mod:
                defs[n] = (mod, v["definition"][:4])
            for u in v.get("usages") or []:
                uses[n].append((mod, u[:4]))

# ---------------------------------------------------------------- sources
_src = {}


def src_lines(m):
    if m not in _src:
        with open(mod_path(m), encoding="utf-8") as f:
            _src[m] = f.read().split("\n")
    return _src[m]


def u16_to_idx(line, col):
    i = 0
    u = 0
    while i < len(line) and u < col:
        u += 2 if ord(line[i]) > 0xFFFF else 1
        i += 1
    return i


def text_at(m, r):
    l0, c0, l1, c1 = r
    lines = src_lines(m)
    if l0 != l1 or l0 >= len(lines):
        return None
    line = lines[l0]
    return line[u16_to_idx(line, c0):u16_to_idx(line, c1)]


# ---------------------------------------------------------------- naming
# Spellings the mechanical rule gets wrong (word boundaries inside one word).
OVERRIDES = {"gmap": "GMap", "gset": "GSet", "mset": "MSet", "rwmutex": "RWMutex"}


def upper_camel(s):
    if s in OVERRIDES:
        return OVERRIDES[s]
    prime = re.search(r"'*$", s).group(0)
    core = s[: len(s) - len(prime)]
    parts = [p for p in core.split("_") if p]
    return "".join(p[:1].upper() + p[1:] for p in parts) + prime


def lower_camel(s):
    prime = re.search(r"'*$", s).group(0)
    core = s[: len(s) - len(prime)]
    parts = [p for p in core.split("_") if p]
    if not parts:
        return s
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:]) + prime


AUX = re.compile(r"^(noConfusionType|noConfusion|below|brecOn|binductionOn|ibelow|casesOn|recOn|rec|"
                 r"ctorIdx|ctorElimType|ctorElim|mk|inj|injEq|sizeOf_spec|eq_\d+|eq_def|"
                 r"_sizeOf_\d+|_sizeOf_inst|match_\d+|proof_\d+|elim)$")


def plain(s):
    return re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*'*", s) is not None


cand = {}   # name -> (module, kind, sort, last)
for n, (m, k, s) in inv.items():
    if is_generated(m) or n not in defs:
        continue
    comps = split_name(n)
    last = comps[-1]
    if not plain(last) or AUX.match(last) or last == "t" or last.startswith("t_"):
        continue
    # Rocq-style encodings of Go names (phase B)
    if any(re.search(r"_Assumptions$", c) or c == "t" or c.startswith("t_") for c in comps[:-1]) \
            or last.endswith("_Assumptions"):
        continue
    if k == "rec":
        continue
    # the user wrote this name: the definition range shows the last component
    t = text_at(*defs[n])
    if t is None or not t.endswith(last):
        continue
    # syntax/macro/tactic declarations keep their names
    if k == "def" and re.match(r"^(tactic|term|command|_aux|wpSpecPat|«)", last):
        continue
    cand[n] = (m, k, s, last)


KEEP = {"Perennial.gmap.dom", "Perennial.GMap.dom"}   # conventional set-like names
# full-name overrides: `go.type` cannot become the keyword `Type`; `val` would clash
# with GooseLang's expression constructor `Val`
FULL_OVERRIDES = {"Perennial.go.type": "GoType", "Perennial.val": "Value"}


def new_last(n):
    m, k, s, last = cand[n]
    if n in KEEP:
        return None if k == "thm" else last
    if n in FULL_OVERRIDES:
        return FULL_OVERRIDES[n]
    if k in ("class", "structure", "inductive") or (k in ("def", "opaque", "axiom") and s in ("Type", "Prop")):
        return upper_camel(last)
    if k in ("def", "opaque", "axiom", "proj", "ctor") and s == "term":
        return lower_camel(last)
    return None   # proofs: handled below


# constructors by inductive (an inductive whose new name equals one of its
# constructors, e.g. `comm_clause` with constructor `CommClause`, keeps its name:
# the exported constructor and the type would be ambiguous)
ctors_of = collections.defaultdict(set)
for n, (m, k, s) in inv.items():
    if k == "ctor":
        ctors_of[".".join(split_name(n)[:-1])].add(split_name(n)[-1])

# first pass: non-proof renames (the vocabulary for theorem names)
rename = {}
for n in cand:
    nl = new_last(n)
    if nl is not None and nl != cand[n][3] and nl not in ctors_of.get(n, ()):
        rename[n] = nl

# ---------------------------------------------------------------- deferral
gen_used = set()
for n, us in uses.items():
    for (mod, _) in us:
        if is_generated(mod):
            gen_used.add(n)
            break


if args.include_generated:
    gen_used = set()


def deferred(n):
    return n in gen_used


vocab = {}   # old multi-word short name -> lowerCamel form, from non-deferred renames
for n, nl in rename.items():
    last = cand[n][3]
    if deferred(n) or "_" not in last.strip("_"):
        continue
    vocab.setdefault(last, set()).add(nl[:1].lower() + nl[1:])
vocab = {k: next(iter(v)) for k, v in vocab.items() if len(v) == 1}
vocab_max = max((k.count("_") + 1 for k in vocab), default=1)


def rewrite_proof_name(last):
    prime = re.search(r"'*$", last).group(0)
    core = last[: len(last) - len(prime)]
    toks = core.split("_")
    out = []
    i = 0
    while i < len(toks):
        hit = None
        # only at the start of the name, or right after `wp_`/`get_`
        ok = i == 0 or (i == 1 and toks[0] in ("wp", "get"))
        for L in (range(min(vocab_max, len(toks) - i), 1, -1) if ok else ()):
            w = "_".join(toks[i:i + L])
            if w in vocab:
                hit = (L, vocab[w])
                break
        if hit:
            out.append(hit[1])
            i += hit[0]
        else:
            out.append(toks[i])
            i += 1
    return "_".join(out) + prime


extra_ns = {}   # name -> extra namespace component (method specs)
shadowed = []
for n, (m, k, s, last) in cand.items():
    if n in rename:
        continue
    if not (k in ("thm", "axiom", "opaque") or s == "proof" or k == "instance"):
        continue
    nl = last
    mm = re.fullmatch(r"wp_([A-Za-z][A-Za-z0-9]*)__(.+)", nl)
    if mm and k != "proj":     # structure fields must stay atomic
        extra_ns[n] = mm.group(1)
        nl = "wp_" + mm.group(2)
    nl = nl.replace("__", "_")
    nl = rewrite_proof_name(nl)
    if nl != last or n in extra_ns:
        rename[n] = nl

for n in list(rename):
    if deferred(n):
        del rename[n]


# Lean keywords (goose's list): such components are written «quoted»
_lg = open(os.path.join(ROOT, "goose/glang/lean.go"), encoding="utf-8").read()
KEYWORDS = set(re.search(r"strings\.Fields\(`([^`]*)`\)", _lg).group(1).split())


def unq(c):
    return c[1:-1] if c.startswith("«") and c.endswith("»") else c


def render(c):
    u = unq(c)
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_'!?]*", u) and u not in KEYWORDS and u != "_":
        return u
    return "«" + u + "»"


def encoding_rename(n):
    """Lean form of a Rocq-style encoded last component (dotted), or None."""
    comps = split_name(n)
    last = comps[-1]
    raw = last[1:-1] if last.startswith("«") and last.endswith("»") else last
    parent = comps[-2] if len(comps) > 1 else ""
    q = render
    # fields of a per-type assumptions class `X_Assumptions`: drop the `X_` prefix
    if parent.endswith("_Assumptions"):
        x = parent[: -len("_Assumptions")]
        if raw == x + "ⁱᵐᵖˡ_underlying":
            return "isUnderlying"
        for pre, rep in ((x + "'ptr_", "ptr_"), (x + "_", "")):
            if raw.startswith(pre) and len(raw) > len(pre):
                return q(rep + raw[len(pre):])
        return None
    # fix-up of an earlier run: X'.impl of a primed type X' is X'.underlying
    if raw == "impl" and len(comps) > 2 and comps[-2].endswith("'") and \
            ".".join(comps[:-2] + [comps[-2].rstrip("'"), "TypeAssumptions"]) in inv:
        return "underlying"
    if raw.endswith("ⁱᵐᵖˡ"):
        base = raw[: -len("ⁱᵐᵖˡ")]
        if "__" in base:
            t, m = base.split("__", 1)
            return ".".join([q(t), q(m), "impl"])
        # the underlying type of a named type (which has an assumptions class,
        # named after the unprimed Go name) is X.underlying (see glang.TypeImpl),
        # a function's body X.impl
        if any(".".join(comps[:-1] + [b + "_Assumptions"]) in inv for b in (base, base.rstrip("'"))):
            return q(base) + ".underlying"
        return q(base) + ".impl"
    for suf, rep in (("'fds_unsealed", "fieldsUnsealed"), ("'fds", "fields"), ("'init", "init")):
        if raw.endswith(suf) and len(raw) > len(suf):
            return q(raw[: -len(suf)]) + "." + rep
    if raw.endswith("_Assumptions") and len(raw) > len("_Assumptions"):
        return q(raw[: -len("_Assumptions")]) + ".TypeAssumptions"
    return None


if args.encodings:
    rename, extra_ns = {}, {}
    for n in inv:
        e = encoding_rename(n)
        if e is not None:
            rename[n] = e

# ---------------------------------------------------------------- full new names
def new_full(n):
    comps = split_name(n)
    out = []
    for i in range(len(comps) - 1):
        pre = ".".join(comps[: i + 1])
        out.extend(split_name(rename[pre]) if pre in rename else [comps[i]])
    if n in extra_ns:
        out.append(extra_ns[n])
    out.extend(split_name(rename[n]) if n in rename else [comps[-1]])
    return out


# constants whose own name is unchanged but whose namespace prefix is renamed
affected = {}
for n in inv:
    comps = split_name(n)
    nf = new_full(n)
    if nf != comps:
        affected[n] = nf

def compute_collisions():
    newnames = collections.defaultdict(list)
    for n, nf in affected.items():
        newnames[".".join(nf)].append(n)
    return {k: v for k, v in newnames.items() if len(v) > 1 or (k in inv and k not in affected)}


# a rename that collides keeps its old name (e.g. `is_Node`/`is_node`, Go names
# that differ only in case); repeat, since dropping one changes its children
def responsible(n):
    """The renames that change the full name of `n`: its own and its prefixes'."""
    comps = split_name(n)
    out = {n} if (n in rename or n in extra_ns) else set()
    for i in range(1, len(comps)):
        pre = ".".join(comps[:i])
        if pre in rename:
            out.add(pre)
    return out


# a new short name equal to the short name of a generated (Go) constant can be
# shadowed by, or ambiguous with, that constant where its package namespace is
# open (e.g. `Header`, `RWMutex`): keep the old name
gen_short = {split_name(n)[-1] for n, (m, k, s) in inv.items() if is_generated(m)}
for n in list(rename):
    if args.encodings:
        break
    if rename[n] in gen_short and rename[n] != cand[n][3]:
        rename.pop(n)
        extra_ns.pop(n, None)
        shadowed.append(n)

dropped = []
deferred_by_child = set()
while True:
    collisions = compute_collisions()
    bad = {n for v in collisions.values() for n in v if n in rename or n in extra_ns}
    # a rename that would change a name used by generated code is deferred,
    # including through a prefix (e.g. an inductive whose constructors goose emits)
    gen = set()
    for n in affected:
        if n in gen_used:
            gen |= responsible(n)
    deferred_by_child |= gen
    if not bad and not gen:
        break
    for n in gen:
        rename.pop(n, None)
        extra_ns.pop(n, None)
    for n in bad:
        dropped.append(n)
        rename.pop(n, None)
        extra_ns.pop(n, None)
    affected = {}
    for n in inv:
        nf = new_full(n)
        if nf != split_name(n):
            affected[n] = nf

# ---------------------------------------------------------------- edits
edits = collections.defaultdict(list)    # module -> [(line, c0, c1, newtext, name)]
skipped = []


def plan_edit(mod, r, n):
    t = text_at(mod, r)
    if t is None:
        skipped.append((mod, r, n, None))
        return
    O = split_name(n)
    N = affected[n]
    lead = ""
    tt = t
    if tt.startswith("@"):
        lead, tt = "@", tt[1:]
    if tt.startswith("_root_."):
        lead, tt = lead + "_root_.", tt[len("_root_."):]
    T = split_name(tt)
    Tu, Ou = [unq(c) for c in T], [unq(c) for c in O]
    if Tu == Ou[-len(T):]:
        hidden = O[: len(O) - len(T)]
        Nh = new_full(".".join(hidden)) if hidden else []
        if N[: len(Nh)] == Nh:
            out = N[len(Nh):]
        else:
            out = N[len(hidden):] if len(N) >= len(hidden) else None
        if out is None:
            skipped.append((mod, r, n, t))
            return
        # keep the source spelling of components that do not change
        k = len(out)
        new = ".".join(T[i - k + len(T)] if 0 <= i - k + len(T) < len(T) and unq(out[i]) == Tu[i - k + len(T)]
                       else render(out[i]) for i in range(k))
    elif T[-1] == O[-1] and n not in extra_ns:
        new = ".".join(T[:-1] + [N[-1]])       # dot notation `x.field`
    else:
        skipped.append((mod, r, n, t))
        return
    if lead + new != t:
        edits[mod].append((r[0], r[1], r[3], lead + new, n))


for n in affected:
    if n in defs and not (args.no_generated_edits and is_generated(defs[n][0])):
        plan_edit(*defs[n], n)
    for (mod, r) in uses.get(n, []):
        if is_generated(mod) and (not args.include_generated or args.no_generated_edits):
            continue
        plan_edit(mod, r, n)

# ---------------------------------------------------------------- report
rep = []
cnt = collections.Counter(cand[n][1] if n in cand else "prefix" for n in affected)
rep.append(f"renamed constants: {len(affected)} {dict(cnt)}")
rep.append(f"deferred (used by generated code): {sum(1 for n in cand if deferred(n) and (new_last(n) or '') not in ('', cand[n][3]))} direct, {len(deferred_by_child)} through a descendant: {sorted(deferred_by_child)[:80]}")
rep.append(f"collisions: {len(collisions)}; kept old name (collision): {sorted(dropped)}")
rep.append(f"kept old name (would be shadowed by a Go name): {sorted(shadowed)}")
for k, v in sorted(collisions.items()):
    rep.append(f"  COLLISION {k} <- {v}")
rep.append(f"edits: {sum(len(v) for v in edits.values())} in {len(edits)} files; skipped refs: {len(skipped)}")
for s in skipped[:200]:
    rep.append(f"  SKIP {s}")
rep.append("")
for n in sorted(affected):
    rep.append(f"{n}\t{'.'.join(affected[n])}")
out = "\n".join(rep)
if args.report:
    open(args.report, "w", encoding="utf-8").write(out + "\n")
print("\n".join(rep[:6 + len(collisions)]))

if not args.apply:
    sys.exit(0)
if collisions:
    sys.exit("refusing to apply with collisions")

for mod, es in edits.items():
    lines = src_lines(mod)
    by_line = collections.defaultdict(list)
    for (l, c0, c1, new, n) in es:
        by_line[l].append((c0, c1, new))
    for l, lst in by_line.items():
        line = lines[l]
        # the same reference can be recorded twice with nested ranges (`@f` and `f`):
        # keep only outermost ranges
        lst = sorted(set(lst), key=lambda e: (e[0], -e[1]))
        outer = []
        for e in lst:
            if outer and e[0] < outer[-1][1]:
                continue
            outer.append(e)
        for c0, c1, new in reversed(outer):
            i0, i1 = u16_to_idx(line, c0), u16_to_idx(line, c1)
            line = line[:i0] + new + line[i1:]
        lines[l] = line
    with open(mod_path(mod), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

# fields referenced inside their own structure/class declaration are local
# names there (no ilean reference): rename them within the declaration block
fields_by_struct = collections.defaultdict(list)
for n in affected:
    if n in cand and cand[n][1] == "proj" and n in defs:
        parent = ".".join(split_name(n)[:-1])
        fields_by_struct[parent].append(n)
for parent, fs in fields_by_struct.items():
    mod = defs[fs[0]][0]
    if parent not in defs or defs[parent][0] != mod:
        continue
    lines = src_lines(mod)
    start = defs[parent][1][0]
    stop = max(defs[f][1][0] for f in fs) + 1
    while stop < len(lines) and (lines[stop].startswith((" ", "\t")) or lines[stop] == "") and \
            not re.match(r"^\S", lines[stop]):
        stop += 1
        if lines[stop - 1] == "":
            break
    subst = {split_name(f)[-1]: affected[f][-1] for f in fs}
    pat = re.compile(r"(?<![\w'.])(" + "|".join(map(re.escape, sorted(subst, key=len, reverse=True))) + r")(?![\w'])")
    for i in range(start, min(stop, len(lines))):
        lines[i] = pat.sub(lambda m: subst[m.group(1)], lines[i])
    with open(mod_path(mod), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

# rename table for the audit (old Rocq-style name -> new name)
with open(os.path.join(ROOT, "etc/lean-rename/renames.tsv"), "a", encoding="utf-8") as f:
    for n in sorted(affected):
        f.write(f"{n}\t{'.'.join(affected[n])}\n")
