"""Second pass: rename namespace components in namespace/end/open/export lines."""
import re, subprocess, sys, collections

ren = [l.rstrip("\n").split("\t") for l in open(sys.argv[1], encoding="utf-8") if "\t" in l]
inv = [l.rstrip("\n").split("\t")[1] for l in open(sys.argv[2], encoding="utf-8")]


def split_name(n):
    return re.split(r"\.(?![^«]*»)", n)


# namespaces: renamed constants that have children
prefixes = set()
for n in inv:
    c = split_name(n)
    for i in range(1, len(c)):
        prefixes.add(".".join(c[:i]))
comp = {}
for o, n in ren:
    if o in prefixes:
        oc, nc = split_name(o), split_name(n)
        if len(oc) == len(nc) and oc[-1] != nc[-1]:
            comp.setdefault(oc[-1], set()).add(nc[-1])
amb = {k for k, v in comp.items() if len(v) > 1}
comp = {k: next(iter(v)) for k, v in comp.items() if k not in amb}
print("namespace components:", len(comp), "ambiguous:", sorted(amb))

files = subprocess.run(["git", "ls-files", "Perennial/*.lean"], capture_output=True, text=True).stdout.split()
LINE = re.compile(r"^(\s*)(namespace|end|section|open|export|open scoped)\b(.*)$")
TOK = re.compile(r"(?<![\w.'«])([A-Za-z_][\w']*(?:\.[A-Za-z_][\w']*)*)")
changed = 0
for f in files:
    with open(f, encoding="utf-8") as h:
        first = h.readline()
        if first.startswith("-- autogenerated"):
            continue
        rest = h.read()
    if f.startswith(("Perennial/Code/", "Perennial/GeneratedProof/", "Perennial/TrustedCode/", "Perennial/ManualProof/")):
        continue
    lines = (first + rest).split("\n")
    dirty = False
    for i, l in enumerate(lines):
        m = LINE.match(l)
        if not m:
            continue
        body = m.group(3)
        # do not touch the parenthesized names of `export X (a b)` / `open X (a)`: those are
        # constants (handled through the ilean references)
        head, paren, tail = body.partition("(")

        def sub(mt):
            parts = mt.group(1).split(".")
            return ".".join(comp.get(p, p) for p in parts)
        nb = TOK.sub(sub, head) + paren + tail
        if nb != body:
            lines[i] = m.group(1) + m.group(2) + nb
            dirty = True
    if dirty:
        changed += 1
        with open(f, "w", encoding="utf-8") as h:
            h.write("\n".join(lines))
print("files changed:", changed)
