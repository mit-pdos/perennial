"""Third pass: leftover qualified old names (in quotations, notations, strings)."""
import re, subprocess, sys

ren = [l.rstrip("\n").split("\t") for l in open(sys.argv[1], encoding="utf-8") if "\t" in l]


def split_name(n):
    return re.split(r"\.(?![^«]*»)", n)


rep = {}
for o, n in ren:
    oc, nc = split_name(o), split_name(n)
    if oc[0] == "Perennial":
        oc, nc = oc[1:], nc[1:]
    # every qualified suffix of the old name with >= 2 components
    for k in range(2, len(oc) + 1):
        os_ = ".".join(oc[-k:])
        extra = len(nc) - len(oc)
        ns_ = ".".join(nc[-(k + extra):])
        if os_ != ns_:
            rep.setdefault(os_, set()).add(ns_)
rep = {k: next(iter(v)) for k, v in rep.items() if len(v) == 1}
keys = sorted(rep, key=len, reverse=True)
pat = re.compile(r"(?<![\w.'«])(" + "|".join(re.escape(k) for k in keys) + r")(?![\w'])")

files = subprocess.run(["git", "ls-files", "Perennial/*.lean"], capture_output=True, text=True).stdout.split()
total = 0
for f in files:
    if f.startswith(("Perennial/Code/", "Perennial/GeneratedProof/", "Perennial/TrustedCode/", "Perennial/ManualProof/")):
        continue
    s = open(f, encoding="utf-8").read()
    if s.startswith("-- autogenerated"):
        continue
    ns, c = pat.subn(lambda m: rep[m.group(1)], s)
    if c:
        total += c
        print(f, c)
        open(f, "w", encoding="utf-8").write(ns)
print("total", total)
