// Command unmodelled writes the unmodelled.go file of a whole-package Go model
// of a standard-library package: every exported declaration of the real
// package (linux/amd64, tags purego) that the model files do not declare,
// with its real signature, so that every caller type-checks against the
// model. Functions and methods get the body gomodel.Stuck() (and a panic
// where a terminating statement is needed); exported struct types whose
// fields are all exported, other exported types and exported constants are
// copied; an exported struct type with unexported fields becomes a
// placeholder struct. It also rewrites the names_only list of the package's
// goose config: the generated functions, methods and placeholder types, and
// every model function whose whole body is that stub.
//
// Usage, from the repository root, with the pinned Go first on PATH:
//
//	go run ./goose/model/overlaytools/unmodelled -pkg reflect \
//		-model goose/model/overlay/reflect -methods-of rtype \
//		-toml Perennial/Code/reflect.toml
//
// -methods-of T also generates, for an unexported type T, the exported
// methods of the real *T, with a value receiver (the model's T implements
// an interface by value).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/importer"
	"go/parser"
	"go/printer"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

const outName = "unmodelled.go"

func main() {
	pkgPath := flag.String("pkg", "", "import path of the standard-library package (required)")
	modelDir := flag.String("model", "", "the model directory (required)")
	methodsOf := flag.String("methods-of", "", "comma-separated unexported types whose real (pointer) methods are generated with value receivers")
	tomlPath := flag.String("toml", "", "goose config whose names_only list is rewritten")
	flag.Parse()
	if *pkgPath == "" || *modelDir == "" {
		flag.Usage()
		os.Exit(2)
	}
	var recvTypes []string
	if *methodsOf != "" {
		recvTypes = strings.Split(*methodsOf, ",")
	}
	if err := run(*pkgPath, *modelDir, recvTypes, *tomlPath); err != nil {
		fmt.Fprintln(os.Stderr, "unmodelled:", err)
		os.Exit(1)
	}
}

func run(pkgPath, modelDir string, recvTypes []string, tomlPath string) error {
	ctx := build.Default
	ctx.GOOS, ctx.GOARCH = "linux", "amd64"
	ctx.BuildTags = []string{"purego"}
	bp, err := ctx.Import(pkgPath, "", 0)
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	var realFiles []*ast.File
	files := slices.Clone(bp.GoFiles)
	sort.Strings(files)
	for _, f := range files {
		af, err := parser.ParseFile(fset, filepath.Join(bp.Dir, f), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		realFiles = append(realFiles, af)
	}
	realPkg, err := importer.ForCompiler(token.NewFileSet(), "source", nil).Import(pkgPath)
	if err != nil {
		return err
	}

	// the model's declarations, and its functions whose body is the stub
	declared := make(map[string]bool)
	var stubs []string
	mfset := token.NewFileSet()
	entries, err := os.ReadDir(modelDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		n := e.Name()
		if !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || n == outName {
			continue
		}
		af, err := parser.ParseFile(mfset, filepath.Join(modelDir, n), nil, 0)
		if err != nil {
			return err
		}
		for _, d := range af.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				declared[funcName(d)] = true
				if isStubBody(d.Body) {
					stubs = append(stubs, funcName(d))
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						declared[s.Name.Name] = true
					case *ast.ValueSpec:
						for _, id := range s.Names {
							declared[id.Name] = true
						}
					}
				}
			}
		}
	}

	g := &gen{fset: fset, imports: make(map[string]string), recvTypes: recvTypes, realPkg: realPkg}
	g.namesOnly = append(g.namesOnly, stubs...)
	for i, f := range realFiles {
		g.file(files[i], f, declared)
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by goose/model/overlaytools/unmodelled; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "// MODEL: the declarations of the real package that the model does not\n"+
		"// model, with their real signatures, so that every caller type-checks.\n"+
		"// Each function and method is names-only (its goose config's names_only):\n"+
		"// goose translates its name and type, not its body, which is\n"+
		"// gomodel.Stuck() for gc builds. A struct type with unexported fields is\n"+
		"// a placeholder, also names-only.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", bp.Name)
	g.imports["internal/gomodel"] = "gomodel"
	var paths []string
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	out.WriteString("import (\n")
	for _, p := range paths {
		if name := g.imports[p]; name != filepath.Base(p) {
			fmt.Fprintf(&out, "\t%s %q\n", name, p)
		} else {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
	}
	out.WriteString(")\n")
	out.Write(g.body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("formatting the output: %v\n%s", err, out.Bytes())
	}
	if err := os.WriteFile(filepath.Join(modelDir, outName), src, 0666); err != nil {
		return err
	}
	if tomlPath != "" {
		return writeNamesOnly(tomlPath, g.namesOnly)
	}
	for _, n := range g.namesOnly {
		fmt.Println(n)
	}
	return nil
}

type gen struct {
	fset      *token.FileSet
	body      bytes.Buffer
	imports   map[string]string // path -> local name
	recvTypes []string
	realPkg   *types.Package
	namesOnly []string
}

func funcName(d *ast.FuncDecl) string {
	if d.Recv == nil || len(d.Recv.List) == 0 {
		return d.Name.Name
	}
	return recvName(d.Recv.List[0].Type) + "." + d.Name.Name
}

func recvName(t ast.Expr) string {
	for {
		switch e := t.(type) {
		case *ast.StarExpr:
			t = e.X
		case *ast.IndexExpr:
			t = e.X
		case *ast.IndexListExpr:
			t = e.X
		case *ast.ParenExpr:
			t = e.X
		case *ast.Ident:
			return e.Name
		default:
			return "?"
		}
	}
}

// isStubBody says whether a body is gomodel.Stuck(), optionally followed by
// panic("unreachable").
func isStubBody(b *ast.BlockStmt) bool {
	if b == nil || len(b.List) == 0 || len(b.List) > 2 {
		return false
	}
	call := func(s ast.Stmt) *ast.CallExpr {
		es, ok := s.(*ast.ExprStmt)
		if !ok {
			return nil
		}
		c, _ := es.X.(*ast.CallExpr)
		return c
	}
	c := call(b.List[0])
	if c == nil {
		return false
	}
	sel, ok := c.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Stuck" || len(c.Args) != 0 {
		return false
	}
	if x, ok := sel.X.(*ast.Ident); !ok || x.Name != "gomodel" {
		return false
	}
	if len(b.List) == 2 {
		p := call(b.List[1])
		if p == nil || len(p.Args) != 1 {
			return false
		}
		if id, ok := p.Fun.(*ast.Ident); !ok || id.Name != "panic" {
			return false
		}
	}
	return true
}

func (g *gen) print(n any) string {
	var b bytes.Buffer
	if err := printer.Fprint(&b, g.fset, n); err != nil {
		panic(err)
	}
	return b.String()
}

// useImports records the imports of f that the identifiers under n use.
func (g *gen) useImports(f *ast.File, n ast.Node) {
	local := make(map[string]string)
	for _, imp := range f.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		name := filepath.Base(p)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		local[name] = p
	}
	ast.Inspect(n, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if x, ok := sel.X.(*ast.Ident); ok {
				if p, ok := local[x.Name]; ok {
					g.imports[p] = x.Name
				}
			}
		}
		return true
	})
}

func (g *gen) file(name string, f *ast.File, declared map[string]bool) {
	var section bytes.Buffer
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			name := funcName(d)
			if declared[name] || !g.wanted(d) {
				continue
			}
			fd := *d
			fd.Doc = nil
			if d.Recv != nil && slices.Contains(g.recvTypes, recvName(d.Recv.List[0].Type)) {
				r := *d.Recv.List[0]
				if s, ok := r.Type.(*ast.StarExpr); ok {
					r.Type = s.X
				}
				fd.Recv = &ast.FieldList{List: []*ast.Field{&r}}
			}
			body := "{\n\tgomodel.Stuck()\n}"
			if d.Type.Results != nil {
				body = "{\n\tgomodel.Stuck()\n\tpanic(\"unreachable\")\n}"
			}
			fd.Body = nil
			g.useImports(f, fd.Type)
			if fd.Recv != nil {
				g.useImports(f, fd.Recv)
			}
			fmt.Fprintf(&section, "\n%s %s\n", g.print(&fd), body)
			g.namesOnly = append(g.namesOnly, name)
		case *ast.GenDecl:
			switch d.Tok {
			case token.TYPE:
				for _, s := range d.Specs {
					ts := s.(*ast.TypeSpec)
					if !ts.Name.IsExported() || declared[ts.Name.Name] {
						continue
					}
					spec := *ts
					spec.Doc, spec.Comment = nil, nil
					if st, ok := ts.Type.(*ast.StructType); ok && !allExported(st) {
						if hasExported(st) {
							panic(fmt.Sprintf("%s: a struct with exported and unexported fields", ts.Name.Name))
						}
						fields := "struct{}"
						if obj := g.realPkg.Scope().Lookup(ts.Name.Name); obj != nil && !types.Comparable(obj.Type()) {
							fields = "struct{ _ [0]func() }"
						}
						fmt.Fprintf(&section, "\ntype %s %s\n", ts.Name.Name, fields)
						g.namesOnly = append(g.namesOnly, ts.Name.Name)
						continue
					}
					g.useImports(f, &spec)
					fmt.Fprintf(&section, "\ntype %s\n", g.print(&spec))
				}
			case token.CONST:
				exported, missing := false, false
				for _, s := range d.Specs {
					for _, id := range s.(*ast.ValueSpec).Names {
						if id.IsExported() {
							exported = true
							missing = missing || !declared[id.Name]
						}
					}
				}
				if !exported || !missing {
					continue
				}
				gd := *d
				gd.Doc = nil
				var specs []ast.Spec
				for _, s := range d.Specs {
					vs := *s.(*ast.ValueSpec)
					vs.Doc, vs.Comment = nil, nil
					specs = append(specs, &vs)
				}
				gd.Specs = specs
				g.useImports(f, &gd)
				fmt.Fprintf(&section, "\n%s\n", g.print(&gd))
			case token.VAR:
				for _, s := range d.Specs {
					for _, id := range s.(*ast.ValueSpec).Names {
						if id.IsExported() && !declared[id.Name] {
							panic(fmt.Sprintf("exported variable %s: not supported", id.Name))
						}
					}
				}
			}
		}
	}
	if section.Len() > 0 {
		fmt.Fprintf(&g.body, "\n// %s\n%s", name, section.Bytes())
	}
}

// wanted says whether a real function is part of the API the model must
// declare: an exported function, an exported method of an exported type, or
// an exported method of one of the -methods-of types.
func (g *gen) wanted(d *ast.FuncDecl) bool {
	if !d.Name.IsExported() {
		return false
	}
	if d.Recv == nil {
		return true
	}
	r := recvName(d.Recv.List[0].Type)
	return token.IsExported(r) || slices.Contains(g.recvTypes, r)
}

func allExported(st *ast.StructType) bool {
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			if !token.IsExported(recvName(f.Type)) {
				return false
			}
		}
		for _, n := range f.Names {
			if !n.IsExported() {
				return false
			}
		}
	}
	return true
}

func hasExported(st *ast.StructType) bool {
	for _, f := range st.Fields.List {
		for _, n := range f.Names {
			if n.IsExported() {
				return true
			}
		}
		if len(f.Names) == 0 && token.IsExported(recvName(f.Type)) {
			return true
		}
	}
	return false
}

var namesOnlyRx = regexp.MustCompile(`(?s)names_only\s*=\s*\[[^\]]*\]`)

// writeNamesOnly replaces the names_only array of a goose config.
func writeNamesOnly(path string, names []string) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !namesOnlyRx.Match(src) {
		return fmt.Errorf("%s has no names_only = [...] to rewrite", path)
	}
	var b strings.Builder
	b.WriteString("names_only = [")
	line := 0
	for i, n := range names {
		q := strconv.Quote(n)
		if i > 0 {
			b.WriteString(",")
			line++
		}
		if line+len(q) > 90 || i == 0 {
			b.WriteString("\n  ")
			line = 2
		} else {
			b.WriteString(" ")
			line++
		}
		b.WriteString(q)
		line += len(q)
	}
	b.WriteString(",\n]")
	out := namesOnlyRx.ReplaceAllLiteral(src, []byte(b.String()))
	return os.WriteFile(path, out, 0666)
}
