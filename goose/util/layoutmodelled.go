// LayoutModelledNames returns the names ("path.Name", sorted) of the types
// whose layout a model changes (Models.LayoutModelled): those of the models
// of the load of patterns, and the type declarations of the packages of
// patterns that their configs trust. Every config in configDir with a
// [model] table or a trusted entry must be the config of a package of
// patterns (else the list could miss a type), except the ones whose path
// relative to configDir is in uncovered.
func LayoutModelledNames(modDir, configDir string, opts LoadOptions, uncovered []string,
	patterns ...string) ([]string, error) {
	models, err := BuildModels(modDir, configDir, opts, patterns...)
	if err != nil {
		return nil, err
	}
	merged, err := models.merge(opts)
	if err != nil {
		return nil, err
	}
	c := NewPackageConfig(modDir, false, merged)
	c.Mode = packages.NeedName | packages.NeedTypes
	pkgs, err := packages.Load(c, patterns...)
	if err != nil {
		return nil, err
	}
	names := make(map[string]bool)
	for n := range models.layoutChanged {
		names[n] = true
	}
	covered := make(map[string]bool)
	var errs ModelErrors
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			errs = append(errs, errors.Errorf("layout-modelled: %s: %v", p.PkgPath, p.Errors))
			continue
		}
		covered[glang.GoPathToIdentPath(p.PkgPath)+".toml"] = true
		scope := p.Types.Scope()
		for _, n := range scope.Names() {
			if o, ok := scope.Lookup(n).(*types.TypeName); ok && !o.IsAlias() {
				if name, ok := models.LayoutModelled(o); ok {
					names[name] = true
				}
			}
		}
	}
	for p := range models.Packages {
		covered[glang.GoPathToIdentPath(p)+".toml"] = true
	}
	for _, u := range uncovered {
		covered[u] = true
	}
	err = filepath.WalkDir(configDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".toml") {
			return err
		}
		rel, err := filepath.Rel(configDir, path)
		if err != nil {
			return err
		}
		contents, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		config, err := declfilter.ParseConfig(contents)
		if err != nil {
			return errors.Wrapf(err, "layout-modelled: %s", rel)
		}
		if (config.Model != nil || len(config.Trusted) > 0) && !covered[filepath.ToSlash(rel)] {
			errs = append(errs, errors.Errorf("layout-modelled: the config %s has a model or a "+
				"trusted declaration, but no package of the patterns has it", rel))
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(errs) > 0 {
		return nil, errs
	}
	var out []string
	for n := range names {
		out = append(out, n)
	}
	sort.Strings(out)
	return out, nil
}

// LayoutModelledLean is the Lean file Perennial/Golang/Defn/LayoutModelled.lean
// of the names of LayoutModelledNames.
func LayoutModelledLean(names []string) []byte {
	var b bytes.Buffer
	b.WriteString(`/-
Generated by goose (` + "`goose layout-modelled`" + `, etc/gen-layout-modelled.sh): do not edit.

The named types whose layout a Go model changes (goose/util.Models.LayoutModelled): the types of
a model's package (goose/model/overlay) whose size, alignment, field offsets (under gc on
linux/amd64) or underlying type differ from the real declaration's, or that the real package
does not declare; and
the types whose declaration a goose config trusts (their Lean definition is in
Perennial/TrustedCode). goose refuses ` + "`unsafe.Sizeof`/`Alignof`/`Offsetof`" + ` of a type containing one, and
reflection treats each as opaque (` + "`go.typeQuery`" + `, Perennial/Golang/Defn/Reflect.lean).
-/
module

public import Perennial.Golang.Defn.PostLang

@[expose] public section

namespace Perennial

namespace go

/-- The names (` + "`path.Name`" + `) of the named types whose layout a Go model changes. -/
def layoutModelledNames : List GoString := [
`)
	for i, n := range names {
		sep := ","
		if i == len(names)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "  go!%q%s\n", n, sep)
	}
	b.WriteString(`]

/-- Whether a Go model changes the layout of ` + "`t`" + `: a named type (with any type arguments) of
` + "`layoutModelledNames`" + `. -/
def layoutModelled (t : go.GoType) : Bool :=
  match t with
  | go.Named n _ => decide (n ∈ layoutModelledNames)
  | _ => false

end go

end Perennial
`)
	return b.Bytes()
}
